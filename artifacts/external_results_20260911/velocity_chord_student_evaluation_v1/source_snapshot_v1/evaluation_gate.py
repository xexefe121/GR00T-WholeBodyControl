"""Require real final70000 artifacts and passed root reviews before model creation.

No binding is generated by draft preparation. Final freeze supplies concrete
existing paths, full hashes and exact pass fields from the completed reviews.
"""
import hashlib
import json
from pathlib import Path
import re
import sys
import numpy as np


def local(path):
    s=str(path).replace('\\','/')
    if sys.platform!='win32' and len(s)>2 and s[1]==':':s='/mnt/'+s[0].lower()+s[2:]
    return Path(s)


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def read(path):return json.loads(Path(path).read_text(encoding='utf-8-sig'))


def bound_file(item):
    if not isinstance(item,dict) or not {'path','sha256'}<=set(item):
        raise ValueError('Concrete path and hash required.')
    if not isinstance(item['sha256'],str) or re.fullmatch('[0-9a-f]{64}',item['sha256']) is None:
        raise ValueError('Full actual artifact SHA256 required.')
    path=local(item['path'])
    if not path.is_absolute() or not path.is_file():raise ValueError('Existing absolute artifact required: '+str(path))
    if sha(path)!=item['sha256']:raise ValueError('Bound evaluation artifact changed: '+str(path))
    return path


def field(value,key):
    for part in key.split('.'):
        if not isinstance(value,dict) or part not in value:raise ValueError('Missing required review field: '+key)
        value=value[part]
    return value


def has_hash(value,digest):
    if isinstance(value,dict):return any(has_hash(v,digest) for v in value.values())
    if isinstance(value,list):return any(has_hash(v,digest) for v in value)
    return value==digest


def require_ready(base):
    base=Path(base)
    path=base/'evaluation_binding.json'
    if not path.is_file():raise ValueError('Final70000 evaluation is unbound; preparation cannot launch it.')
    binding=read(path)
    assert binding['root_authorized_canonical_evaluation'] is True
    assert binding['ordinary_final_step']==70000
    assert binding['requested_main_controls']==1569 and binding['conditional_hold_controls']==250
    assert binding['hardware_authorized'] is False
    assert binding['controller']=='original_unfiltered_raw_combined_action'
    assert binding['filters_enabled'] is False and binding['compiled_preview_enabled'] is False
    required=('head','checkpoint','fit_report','training_manifest','first_export_witness','first_export_receipt')
    paths={name:bound_file(binding[name]) for name in required}
    for entry in binding['input_files']:bound_file(entry)
    expected_subjects=dict(fit=binding['fit_report']['sha256'],export=binding['head']['sha256'],
        source=sha(base/'source_snapshot_v1/evaluate_velocity_chord_student.py'))
    for role in ('dataset','fit','source','export'):
        entry=binding['reviews'][role]
        review=read(bound_file(entry))
        assert isinstance(entry['pass_field'],str) and entry['pass_field']
        if field(review,entry['pass_field']) is not True:
            raise ValueError('Root '+role+' review has not passed.')
        if role in expected_subjects and not has_hash(review,expected_subjects[role]):
            raise ValueError('Root '+role+' review does not bind the actual final subject.')
        if role=='dataset':
            assert binding['training_dataset_sha256']
            for digest in binding['training_dataset_sha256']:
                assert re.fullmatch('[0-9a-f]{64}',digest) and has_hash(review,digest)
    fit=read(paths['fit_report'])
    assert fit['ordinary_final_step']==70000 and fit['additional_updates']==5000
    for key in ('optimization_completed','final_export_diagnostics_completed','numerical_gate_passed','export_parity_passed'):
        assert fit[key] is True,key
    assert fit['checkpoint_sha256']==binding['checkpoint']['sha256']
    assert fit['onnx_sha256']==binding['head']['sha256']
    export=read(paths['first_export_receipt'])
    assert export['pass_all'] is True
    assert export['expected_head_calls']==1 and export['attempted_head_calls']==1
    assert export['BFM_inference_calls']==0 and export['physics_steps']==0
    assert export['fit_head_calls_repeated']==0 and export['fitting_launched'] is False
    assert export['head_sha256']==binding['head']['sha256']
    assert export['witness_sha256']==binding['first_export_witness']['sha256']
    assert export['control']==250 and export['source_frame']==261
    assert export['onnxruntime_version']=='1.23.2' and export['intra_op_threads']==1
    assert export['inter_op_threads']==1 and export['execution_mode']=='ORT_SEQUENTIAL'
    assert export['execution_provider']=='CPUExecutionProvider'
    assert export['pinned_WSL_runtime'] is True
    with np.load(paths['first_export_witness'],allow_pickle=False) as data:
        witness={key:data[key].copy() for key in data.files}
    assert witness['features'].shape==(1069,) and witness['features'].dtype==np.float32
    assert witness['onnx_delta'].shape==(23,) and witness['onnx_delta'].dtype==np.float32
    assert np.isfinite(witness['features']).all() and np.isfinite(witness['onnx_delta']).all()
    assert int(witness['control'])==250 and int(witness['source_frame'])==261
    assert str(witness['head_sha256'].item())==binding['head']['sha256']
    assert str(witness['runtime_binary_sha256'].item())==export['runtime_binary_sha256']
    assert any(item['sha256']==export['runtime_binary_sha256'] for item in binding['input_files'])
    return dict(binding=binding,binding_path=path,binding_sha256=sha(path),head=paths['head'],
                fit_report=fit,first_export=witness)
